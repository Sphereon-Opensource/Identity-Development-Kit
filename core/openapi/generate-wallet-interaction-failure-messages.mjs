#!/usr/bin/env node
/**
 * Generates TypeScript from wallet-interaction-failure-messages.json.
 *
 * The JSON is the canonical catalogue (keyed on code, never messageKey). Gradle in
 * lib-wallet-interaction-public generates the Kotlin half. This command is the TypeScript half.
 *
 * Usage (from the frontend repo, after the openapi-canonical mirror has the JSON):
 *
 *   node packages/wallet/packages/vdx-shared/openapi-canonical/generate-wallet-interaction-failure-messages.mjs --lang ts --out packages/enterprise-shared-ui/src/holder/failureMessages.generated.ts
 *
 * From this directory:
 *
 *   node generate-wallet-interaction-failure-messages.mjs --lang ts --out failureMessages.generated.ts
 */

import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);

function argValue(flag, fallback) {
  const index = args.indexOf(flag);
  if (index === -1 || index === args.length - 1) return fallback;
  return args[index + 1];
}

const lang = argValue("--lang", "ts");
const out = argValue("--out", null);

if (lang !== "ts") {
  console.error("Only --lang ts is implemented here. Kotlin is generated by Gradle: :lib-wallet-interaction-public:generateWalletInteractionFailureCatalogue");
  process.exitCode = 1;
  process.exit();
}

if (out == null) {
  console.error("Missing --out <file>");
  process.exitCode = 1;
  process.exit();
}

const catalogue = JSON.parse(await readFile(resolve(root, "wallet-interaction-failure-messages.json"), "utf8"));
const defaultLocale = catalogue.defaultLocale;
if (typeof defaultLocale !== "string" || defaultLocale.length === 0) {
  throw new Error("defaultLocale must be a non-empty string");
}

const dispositions = ["TERMINAL", "REPEATABLE", "RESUMABLE"];
const byDisposition = catalogue.byDisposition ?? {};
const byCode = catalogue.byCode ?? {};

function localesOf(table) {
  const locales = new Set();
  for (const entry of Object.values(table)) {
    if (entry && typeof entry === "object") {
      for (const locale of Object.keys(entry)) locales.add(locale);
    }
  }
  return [...locales].sort();
}

const locales = [...new Set([defaultLocale, ...localesOf(byDisposition), ...localesOf(byCode)])].sort();

function escapeTs(value) {
  return value.replace(/\\/gu, "\\\\").replace(/'/gu, "\\'").replace(/\n/gu, "\\n");
}

function copyFor(table, key, locale) {
  const entry = table[key];
  if (entry == null || typeof entry !== "object") {
    throw new Error(`Missing catalogue entry ${key}`);
  }
  const text = entry[locale] ?? entry[defaultLocale];
  if (typeof text !== "string" || text.trim() === "") {
    throw new Error(`Catalogue entry ${key} has no non-empty string for ${locale}`);
  }
  return text;
}

function recordBlock(keys, lookup, indent) {
  const pad = " ".repeat(indent);
  const lines = keys.map((key, index) => {
    const comma = index === keys.length - 1 ? "," : ",";
    return `${pad}'${escapeTs(key)}': '${escapeTs(lookup(key))}'${comma}`;
  });
  return lines.join("\n");
}

const codeKeys = Object.keys(byCode).sort();
const defaultDispositionRecord = recordBlock(dispositions, (key) => copyFor(byDisposition, key, defaultLocale), 2);
const defaultCodeRecord = recordBlock(codeKeys, (key) => copyFor(byCode, key, defaultLocale), 2);

const dispositionByLocale = locales
  .map((locale) => {
    const body = recordBlock(dispositions, (key) => copyFor(byDisposition, key, locale), 4);
    return `  '${escapeTs(locale)}': {\n${body}\n  },`;
  })
  .join("\n");

const codeByLocale = locales
  .map((locale) => {
    const body = recordBlock(codeKeys, (key) => copyFor(byCode, key, locale), 4);
    return `  '${escapeTs(locale)}': {\n${body}\n  },`;
  })
  .join("\n");

const generated = `/**
 * GENERATED from wallet-interaction-failure-messages.json. Do not edit.
 *
 * Holder-facing failure copy, keyed on \`code\` never \`messageKey\`. Resolve CLIENT side in the
 * device locale. \`message\` is the first rung: a backend-resolved string still wins.
 */

export type InteractionFailureDisposition = 'TERMINAL' | 'REPEATABLE' | 'RESUMABLE'

export interface FailureCopy {
  byDisposition: Record<InteractionFailureDisposition, string>
  byCode?: Readonly<Record<string, string>>
}

export const DEFAULT_LOCALE = '${escapeTs(defaultLocale)}' as const

export const DEFAULT_FAILURE_BY_DISPOSITION: Record<InteractionFailureDisposition, string> = {
${defaultDispositionRecord}
}

export const DEFAULT_FAILURE_BY_CODE: Readonly<Record<string, string>> = {
${defaultCodeRecord}
}

const BY_DISPOSITION_BY_LOCALE: Record<string, Record<InteractionFailureDisposition, string>> = {
${dispositionByLocale}
}

const BY_CODE_BY_LOCALE: Record<string, Readonly<Record<string, string>>> = {
${codeByLocale}
}

function localize<T>(table: Record<string, T>, locale: string, fallback: T): T {
  if (table[locale] !== undefined) return table[locale]
  const language = locale.split(/[-_]/u)[0]
  if (language && language !== locale && table[language] !== undefined) return table[language]
  return table[DEFAULT_LOCALE] ?? fallback
}

export function failureCopyForLocale(locale: string = DEFAULT_LOCALE): FailureCopy {
  return {
    byDisposition: localize(BY_DISPOSITION_BY_LOCALE, locale, DEFAULT_FAILURE_BY_DISPOSITION),
    byCode: localize(BY_CODE_BY_LOCALE, locale, DEFAULT_FAILURE_BY_CODE),
  }
}

export function resolveFailureMessage(
  failure: {disposition: InteractionFailureDisposition; message?: string; code?: string},
  copy: FailureCopy = failureCopyForLocale(),
): string {
  if (failure.message !== undefined && failure.message !== '') return failure.message
  const specific = failure.code !== undefined ? copy.byCode?.[failure.code] : undefined
  if (specific !== undefined) return specific
  return copy.byDisposition[failure.disposition]
}
`;

const destination = resolve(process.cwd(), out);
await writeFile(destination, generated, "utf8");
console.log(`Wrote TypeScript catalogue to ${destination}`);
